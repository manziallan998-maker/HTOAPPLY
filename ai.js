// ── AI UNIVERSITY MATCHER ──
function matchUniversities() {
  const grades = parseFloat(document.getElementById('matchGrades').value) || 0;
  const budget = parseFloat(document.getElementById('matchBudget').value) || 50000;
  const program = document.getElementById('matchProgram').value.toLowerCase();
  const countries = document.getElementById('matchCountries').value.toLowerCase();

  // Rules-based matching engine
  let matches = UNIVERSITIES_DATA.filter(uni => {
    // Budget filter
    if (uni.tuition_usd > budget) return false;
    // Program filter
    if (program && !uni.degrees.some(d => d.toLowerCase().includes(program))) return false;
    // Country preference
    if (countries && !uni.country.toLowerCase().includes(countries)) return false;
    return true;
  });

  // Sort by ranking
  matches.sort((a, b) => a.ranking - b.ranking);

  // Score each match
  const scoredMatches = matches.map(uni => {
    let score = 100;
    // Ranking bonus
    if (uni.ranking <= 100) score += 30;
    else if (uni.ranking <= 500) score += 20;
    else if (uni.ranking <= 1000) score += 10;
    // Budget fit
    const budgetRatio = uni.tuition_usd / budget;
    if (budgetRatio < 0.5) score += 20;
    else if (budgetRatio < 0.8) score += 10;
    return { ...uni, score };
  });

  scoredMatches.sort((a, b) => b.score - a.score);

  const output = document.getElementById('matchOutput');
  if (scoredMatches.length === 0) {
    output.innerHTML = `<div class="empty-state"><div class="icon">🔍</div><h3>No matches found</h3><p>Try adjusting your budget or program preferences</p></div>`;
  } else {
    output.innerHTML = `
      <div style="font-weight:600;margin-bottom:16px">🎯 Found ${scoredMatches.length} matching universities:</div>
      ${scoredMatches.slice(0, 6).map((uni, i) => `
        <div style="display:flex;align-items:center;gap:14px;padding:14px;background:var(--bg-card);border:1px solid var(--border);border-radius:var(--radius-sm);margin-bottom:10px">
          <div style="width:28px;height:28px;background:var(--gradient-2);border-radius:50%;display:flex;align-items:center;justify-content:center;font-weight:800;font-size:0.8rem;color:white;flex-shrink:0">${i+1}</div>
          <span style="font-size:1.4rem">${uni.flag}</span>
          <div style="flex:1">
            <div style="font-weight:600;font-size:0.92rem">${uni.name}</div>
            <div style="font-size:0.8rem;color:var(--text-secondary)">${uni.country} • Rank #${uni.ranking} • ${uni.tuition}/yr</div>
          </div>
          <span class="tag tag-green">${uni.score}% match</span>
        </div>
      `).join('')}
    `;
  }
  output.classList.add('show');
}
