// ── AI TOOLS (powered by Anthropic API via Supabase Edge or direct) ──

async function callAI(prompt, outputId, loadingId) {
  const output = document.getElementById(outputId);
  const loading = document.getElementById(loadingId);

  output.classList.remove('show');
  loading.style.display = 'flex';

  try {
    const response = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: 'claude-sonnet-4-20250514',
        max_tokens: 1000,
        messages: [{ role: 'user', content: prompt }]
      })
    });

    const data = await response.json();

    if (data.error) {
      // Fallback: generate locally for demo if API call fails
      return generateFallback(prompt, outputId, loadingId);
    }

    const text = data.content?.map(c => c.text || '').join('') || '';
    loading.style.display = 'none';
    output.textContent = text;
    output.classList.add('show');
    showToast('AI content generated!', 'success');
    await logActivity('Used AI Tool');
    return text;
  } catch (err) {
    return generateFallback(prompt, outputId, loadingId);
  }
}

function generateFallback(prompt, outputId, loadingId) {
  const output = document.getElementById(outputId);
  const loading = document.getElementById(loadingId);

  // Context-aware fallback content
  let text = '';
  if (prompt.includes('CV') || prompt.includes('resume')) {
    text = generateSampleCV(prompt);
  } else if (prompt.includes('personal statement')) {
    text = generateSamplePS(prompt);
  } else if (prompt.includes('motivation letter')) {
    text = generateSampleML(prompt);
  } else {
    text = `[AI Preview Mode]\n\nThis is a preview of the AI-generated content. Connect your Anthropic API key in Supabase Edge Functions to enable full AI generation.\n\nYour input has been received and would be processed by Claude AI to generate professional, personalized content tailored to your academic background and goals.`;
  }

  setTimeout(() => {
    loading.style.display = 'none';
    output.textContent = text;
    output.classList.add('show');
  }, 1500);
}

